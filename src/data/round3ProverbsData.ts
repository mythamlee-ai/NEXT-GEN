/**
 * Helper to convert Round3ProverbItem to PicturePuzzle compatible format
 */
export function proverbToPicturePuzzle(item: Round3ProverbItem): PicturePuzzle {
  return {
    id: item.id,
    round: 3,
    topic: `Ca Dao Tục Ngữ #${item.proverbNumber.toString().padStart(2, '0')}: ${item.topic}`,
    type: 'text',
    image: '', // Visual is rendered dynamically from visualClues
    question: `ĐUỔI HÌNH BẮT CHỮ: Hãy nhìn các biểu tượng 3D phát sáng và giải mã câu ca dao / tục ngữ Việt Nam tương ứng!`,
    hint: `Thuộc chủ đề: ${item.category} (${item.difficulty.toUpperCase()})`,
    acceptedAliases: item.acceptedAnswers,
    correctAnswer: item.answer,
    explanation: `Đáp án chính xác: "${item.answer}" — Một bài học dân gian quý báu về ${item.topic.toLowerCase()}.`,
    points: item.points,
    timeLimit: item.timeLimit,
    active: item.active,
    proverbNumber: item.proverbNumber,
    visualClues: item.visualClues,
    answer: item.answer,
    acceptedAnswers: item.acceptedAnswers,
    difficulty: item.difficulty,
    category: item.category,
    usageCount: item.usageCount,
  };
}

export const defaultProverbPuzzles: PicturePuzzle[] = FORTY_OFFICIAL_PROVERBS.map(proverbToPicturePuzzle);
